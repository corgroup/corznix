-- ---- deterministic backfill of code FKs where the existing free-text
--      label is an EXACT match for an approved reference (brief §30 step 3).
--      Ambiguous / unmapped values stay NULL and surface in the Phase 1B
--      migration-readiness report as NEEDS_*_MAPPING. Design codes are NEVER
--      inferred (brief §24).

UPDATE products p
  JOIN catalog_product_type_codes t
    ON t.code = CASE LOWER(p.product_type)
      WHEN 'tshirts' THEN 'TS'
      WHEN 't-shirts' THEN 'TS'
      WHEN 't-shirt' THEN 'TS'
      WHEN 'tshirt' THEN 'TS'
      WHEN 'shirts' THEN 'SH'
      WHEN 'shirt' THEN 'SH'
      WHEN 'jeans' THEN 'JN'
      ELSE NULL END
  SET p.product_type_code_id = t.id
  WHERE p.product_type_code_id IS NULL;

UPDATE products p
  JOIN catalog_fit_codes f
    ON f.code = CASE LOWER(p.fit)
      WHEN 'regular fit' THEN 'R'
      WHEN 'regular' THEN 'R'
      WHEN 'slim fit' THEN 'S'
      WHEN 'slim' THEN 'S'
      WHEN 'oversize fit' THEN 'O'
      WHEN 'oversized fit' THEN 'O'
      WHEN 'oversize' THEN 'O'
      WHEN 'oversized' THEN 'O'
      WHEN 'relaxed fit' THEN 'RLX'
      WHEN 'relaxed' THEN 'RLX'
      ELSE NULL END
  SET p.fit_code_id = f.id
  WHERE p.fit_code_id IS NULL;

UPDATE product_variants v
  JOIN catalog_color_codes c ON LOWER(c.label) = LOWER(v.color_name)
  SET v.color_code_id = c.id
  WHERE v.color_code_id IS NULL AND v.color_name IS NOT NULL AND v.color_name <> '';

-- ---- backfill invoice_items.sku_id (no rows today; safety net) ------
UPDATE invoice_items ii
  JOIN invoices inv ON inv.id = ii.invoice_id
  JOIN order_items oi ON oi.order_id = inv.order_id AND oi.sku = ii.sku
  SET ii.sku_id = oi.sku_id
  WHERE ii.sku_id IS NULL
    AND (SELECT COUNT(DISTINCT oi2.sku_id) FROM order_items oi2 WHERE oi2.order_id = inv.order_id AND oi2.sku = ii.sku) = 1;
